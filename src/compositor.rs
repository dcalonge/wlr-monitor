/// The generated compositor config (or its state file) cannot be written.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CompositorError {
    pub message: String,
    /// The include was written, only the sidecar state file was not. The
    /// compositor already has the new layout, so callers treat this as a
    /// warning rather than a failed apply.
    pub state_file: bool,
}

impl CompositorError {
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
            state_file: false,
        }
    }
}

impl fmt::Display for CompositorError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for CompositorError {}

/// Anything that can stop an apply before it ran.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ApplyError {
    Wlr(WlrRandrError),
    Compositor(CompositorError),
}

impl fmt::Display for ApplyError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Wlr(error) => error.fmt(f),
            Self::Compositor(error) => error.fmt(f),
        }
    }
}

impl std::error::Error for ApplyError {}

impl From<WlrRandrError> for ApplyError {
    fn from(error: WlrRandrError) -> Self {
        Self::Wlr(error)
    }
}

impl From<CompositorError> for ApplyError {
    fn from(error: CompositorError) -> Self {
        Self::Compositor(error)
    }
}

/// Compositor-specific settings the integration can manage.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Capabilities {
    pub hdr: bool,
    pub bit_depths: Vec<i64>,
    pub color_presets: Vec<String>,
    pub icc: bool,
}

impl Capabilities {
    pub fn color_profile(&self) -> bool {
        !self.color_presets.is_empty() || self.icc
    }
}

/// Information shared by all outputs while rendering one include.
///
/// `ambiguous` holds EDID identifiers used by more than one output (those
/// must be matched by connector name instead). `preserved` maps a match
/// target to option lines the user added by hand to the previous include.
#[derive(Debug, Clone, Default)]
pub struct RenderContext {
    pub ambiguous: HashSet<String>,
    pub preserved: HashMap<String, Vec<String>>,
}

impl RenderContext {
    fn preserved(&self, target: &str) -> &[String] {
        self.preserved.get(target).map_or(&[], Vec::as_slice)
    }
}

/// Refresh rate with the three decimals sway, niri and mango expect.
pub fn format_refresh_config(value: f64) -> String {
    format!("{value:.3}")
}

pub fn color_profile_label(value: Option<&str>) -> String {
    match value {
        None | Some("") => "default".to_string(),
        Some(value) => match value.strip_prefix("icc:") {
            Some(path) => format!("ICC {path}"),
            None => value.to_string(),
        },
    }
}

/// Replace `path` with `text` unless it already has that content.
fn write_if_changed(path: &Path, text: &str, display: &str) -> Result<(), CompositorError> {
    let error =
        |error: io::Error| CompositorError::new(format!("Could not write {display}: {error}"));
    if fs::read(path).is_ok_and(|current| current == text.as_bytes()) {
        return Ok(());
    }
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        paths::mkdir_parents(parent).map_err(error)?;
    }
    paths::atomic_write(path, text.as_bytes(), 0o644).map_err(error)
}

/// Run an IPC query and decode its JSON output, or return `None`.
pub fn query(command: &[String], env: Option<&HashMap<String, String>>) -> Option<Value> {
    let done = crate::process::run(command, QUERY_TIMEOUT, env).ok()?;
    if !done.success() {
        return None;
    }
    serde_json::from_str(&done.stdout).ok()
}

/// The supported compositors, in the order `--compositor` lists them.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// A generic wlroots compositor: everything goes through wlr-randr.
    Wlroots,
    Mango,
    Sway,
    Niri,
}

impl Kind {
    pub const ALL: [Kind; 4] = [Kind::Wlroots, Kind::Mango, Kind::Sway, Kind::Niri];

    pub fn name(self) -> &'static str {
        match self {
            Self::Wlroots => "wlroots",
            Self::Mango => "mango",
            Self::Sway => "sway",
            Self::Niri => "niri",
        }
    }

    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL
            .into_iter()
            .find(|kind| kind.name().eq_ignore_ascii_case(name))
    }

    fn tool(self) -> &'static str {
        match self {
            Self::Wlroots => "",
            Self::Mango => "mmsg",
            Self::Sway => "swaymsg",
            Self::Niri => "niri",
        }
    }

    fn config_dir(self) -> &'static str {
        match self {
            Self::Wlroots => "",
            Self::Mango => "mango",
            Self::Sway => "sway",
            Self::Niri => "niri",
        }
    }

    fn include_filename(self) -> &'static str {
        match self {
            Self::Wlroots => "",
            Self::Mango | Self::Sway => "wlr-monitor.conf",
            Self::Niri => "wlr-monitor.kdl",
        }
    }

    fn comment(self) -> &'static str {
        match self {
            Self::Niri => "//",
            _ => "#",
        }
    }

    fn note(self) -> &'static str {
        match self {
            Self::Wlroots => "",
            Self::Mango => {
                "Extra rule options you add (hdr_max_lum, primary, …) are kept on rewrite."
            }
            Self::Sway => "sway merges output commands: put bg, max_render_time, … in your config.",
            Self::Niri => {
                "niri uses the first matching output block: add layout {}, hot-corners, … here; they are kept."
            }
        }
    }

    pub fn default_capabilities(self) -> Capabilities {
        match self {
            Self::Wlroots => Capabilities::default(),
            Self::Mango => Capabilities {
                hdr: true,
                icc: true,
                ..Capabilities::default()
            },
            Self::Sway => Capabilities {
                hdr: true,
                bit_depths: vec![6, 8, 10],
                color_presets: vec!["gamma22".into(), "srgb".into()],
                icc: true,
            },
            // niri has no HDR or color management yet; max-bpc is the depth.
            Self::Niri => Capabilities {
                bit_depths: vec![6, 8, 10, 12, 14, 16],
                ..Capabilities::default()
            },
        }
    }
}

