    /// Render the include for exactly `outputs` (see `layout_for_include`).
    pub fn render_include(
        &self,
        outputs: &[Output],
        profile: Option<&str>,
    ) -> Result<String, CompositorError> {
        let comment = self.kind.comment();
        let mut lines = vec![format!("{comment} {HEADER}")];
        let note = self.kind.note();
        if !note.is_empty() {
            lines.push(format!("{comment} {note}"));
        }
        if let Some(profile) = profile.filter(|p| !p.is_empty()) {
            // Profile names end up in a config file: never let them add lines.
            let safe: String = profile
                .chars()
                .filter(|c| crate::text::is_printable(*c))
                .collect();
            lines.push(format!("{comment} Profile: {safe}"));
        }
        lines.push(String::new());
        let context = self.render_context(outputs, self.preserved_options()?);
        for output in outputs {
            lines.extend(self.render_output(output, &context)?);
        }
        Ok(format!("{}\n", lines.join("\n").trim_end_matches('\n')))
    }

    pub fn render_context(
        &self,
        outputs: &[Output],
        preserved: HashMap<String, Vec<String>>,
    ) -> RenderContext {
        let mut counts: HashMap<String, usize> = HashMap::new();
        for output in outputs {
            let identifier = output.identifier();
            if !identifier.is_empty() {
                *counts.entry(identifier).or_default() += 1;
            }
        }
        RenderContext {
            ambiguous: counts
                .into_iter()
                .filter(|(_, count)| *count > 1)
                .map(|(key, _)| key)
                .collect(),
            preserved,
        }
    }

    /// Name used to match an output in the generated config.
    ///
    /// The EDID identifier survives connector renames (docks, MST hubs). It
    /// is skipped when two outputs share it (identical monitors often report
    /// the same serial) and when it is not printable, since EDID strings come
    /// from the monitor and must not be able to add config lines.
    pub fn target(
        &self,
        output: &Output,
        context: &RenderContext,
    ) -> Result<String, CompositorError> {
        let identifier = output.identifier();
        if !identifier.is_empty()
            && !context.ambiguous.contains(&identifier)
            && printable(&identifier)
        {
            return Ok(identifier);
        }
        unprintable_name_check(&output.name)?;
        Ok(output.name.clone())
    }

    fn render_output(
        &self,
        output: &Output,
        context: &RenderContext,
    ) -> Result<Vec<String>, CompositorError> {
        match self.kind {
            Kind::Wlroots => Ok(Vec::new()),
            Kind::Sway => {
                let target = self.target(output, context)?;
                Ok(vec![format!(
                    "output {} {}",
                    quote(&target),
                    self.sway_output_args(&output.state())?
                )])
            }
            Kind::Niri => self.niri_render_output(output, context),
            Kind::Mango => self.mango_render_output(output, context),
        }
    }

    /// Hand-added options in the current include, keyed by match target.
    ///
    /// An include that is not valid UTF-8 is an error rather than empty:
    /// rewriting it would silently drop the user's own options.
    pub fn preserved_options(&self) -> Result<HashMap<String, Vec<String>>, CompositorError> {
        Ok(match self.kind {
            Kind::Niri => niri_preserved(&self.read_include_text()?),
            Kind::Mango => mango_preserved(&self.read_include_text()?),
            _ => HashMap::new(),
        })
    }

    fn read_include_text(&self) -> Result<String, CompositorError> {
        let Some(path) = self.include_path() else {
            return Ok(String::new());
        };
        // A missing or unreadable file has nothing to preserve.
        let Ok(bytes) = fs::read(&path) else {
            return Ok(String::new());
        };
        String::from_utf8(bytes).map_err(|_| {
            CompositorError::new(format!(
                "Could not read {}: it is not valid UTF-8.",
                self.display_path(&path)
            ))
        })
    }

    /// Reject values that would not be safe to put in a config or command.
    ///
    /// Profiles are plain JSON files, so their strings are untrusted input.
    pub fn check_state(&self, state: &OutputState) -> Result<(), CompositorError> {
        if !TRANSFORMS.contains(&state.transform.as_str()) {
            return Err(CompositorError::new(format!(
                "{}: invalid transform {}.",
                state.name,
                repr(&state.transform)
            )));
        }
        if !printable(&state.name) {
            return Err(CompositorError::new(format!(
                "Invalid output name {}.",
                repr(&state.name)
            )));
        }
        Ok(())
    }

    fn sidecar_entry(output: &Output) -> Value {
        let mut entry = output.state().to_dict();
        entry.insert("make".into(), Value::String(output.make.clone()));
        entry.insert("model".into(), Value::String(output.model.clone()));
        entry.insert("serial".into(), Value::String(output.serial.clone()));
        Value::Object(entry)
    }

    /// Outputs from the previous include that are not connected now.
    ///
    /// Keeping their rules means a dock monitor still gets its layout after
    /// the user applied something while undocked.
    pub fn retained_outputs(&self, current: &[Output]) -> Vec<Output> {
        let saved = self.saved_outputs();
        if saved.is_empty() {
            return Vec::new();
        }
        let names: HashSet<&str> = current.iter().map(|output| output.name.as_str()).collect();
        let connected: Vec<String> = current
            .iter()
            .map(Output::hardware_id)
            .filter(|id| !id.is_empty())
            .collect();
        let mut saved_hardware: HashMap<String, usize> = HashMap::new();
        for raw in saved.values().filter(|raw| raw.is_object()) {
            *saved_hardware
                .entry(loose_str(raw.get("hardware_id")))
                .or_default() += 1;
        }
        let mut retained = Vec::new();
        for (name, raw) in &saved {
            if !raw.is_object() || names.contains(name.as_str()) {
                continue;
            }
            let Ok(state) = OutputState::from_dict(name, raw) else {
                continue;
            };
            // The same monitor, now on another connector. Only trusted when
            // the EDID id is unique: identical monitors often share a serial,
            // and dropping the twin's rule would merge both onto one rule.
            if !state.hardware_id.is_empty()
                && saved_hardware.get(&state.hardware_id) == Some(&1)
                && connected.contains(&state.hardware_id)
            {
                continue;
            }
            let mut output = Output::new(name.clone());
            output.description = state.description.clone();
            output.make = loose_str(raw.get("make"));
            output.model = loose_str(raw.get("model"));
            output.serial = loose_str(raw.get("serial"));
            state.apply_to(&mut output, true);
            output.mode = state.mode.clone();
            retained.push(output);
        }
        retained
    }

    /// `outputs` plus the remembered disconnected ones, validated.
    ///
    /// This is exactly what `write_include()` writes, so `--print-config`
    /// can show the same thing.
    pub fn layout_for_include(&self, outputs: &[Output]) -> Result<Vec<Output>, CompositorError> {
        let mut items = outputs.to_vec();
        items.extend(self.retained_outputs(outputs));
        for output in &items {
            self.check_state(&output.state())?;
        }
        Ok(items)
    }

    /// Atomically write the include. Returns the path, or `None` if disabled.
    ///
    /// Returns a `state_file` error when only the sidecar could not be
    /// written; the include itself is already in place then.
    pub fn write_include(
        &self,
        outputs: &[Output],
        profile: Option<&str>,
    ) -> Result<Option<PathBuf>, CompositorError> {
        let Some(path) = self.include_path() else {
            return Ok(None);
        };
        if !self.write_include_enabled {
            return Ok(None);
        }
        let items = self.layout_for_include(outputs)?;
        let text = self.render_include(&items, profile)?;
        if path
            .symlink_metadata()
            .is_ok_and(|meta| meta.file_type().is_symlink())
        {
            return Err(CompositorError::new(format!(
                "{} is a symlink (managed by Home Manager or NixOS?). wlr-monitor needs a \
                 writable file; remove the link or pass --include to choose another path.",
                self.display_path(&path)
            )));
        }
        let mut state = Map::new();
        state.insert(
            "profile".into(),
            profile.map_or(Value::Null, |p| Value::String(p.to_string())),
        );
        state.insert(
            "include".into(),
            Value::String(path.to_string_lossy().into_owned()),
        );
        let entries: Map<String, Value> = items
            .iter()
            .map(|output| (output.name.clone(), Self::sidecar_entry(output)))
            .collect();
        state.insert("outputs".into(), Value::Object(entries));

        write_if_changed(&path, &text, &self.display_path(&path))?;
        let state_path = self.state_path();
        let state_text = format!("{}\n", to_pretty_json(&sorted(Value::Object(state))));
        write_if_changed(&state_path, &state_text, &self.display_path(&state_path)).map_err(
            |error| CompositorError {
                message: format!(
                    "{error}. The include was written, but color settings and disconnected \
                     outputs will not be remembered."
                ),
                state_file: true,
            },
        )?;
        Ok(Some(path))
    }

    /// Write the include after a successful live apply.
    fn persist(
        &self,
        results: &[ApplyResult],
        layout: &[Output],
        profile: Option<&str>,
    ) -> Vec<ApplyResult> {
        if layout.is_empty() || results.iter().any(|result| !result.ok) {
            return Vec::new();
        }
        match self.write_include(layout, profile) {
            Ok(_) => Vec::new(),
            Err(error) => vec![config_warning(error.message)],
        }
    }

