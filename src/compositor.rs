    pub fn apply(
        &self,
        wlr: &dyn Wlr,
        states: &[OutputState],
        layout: &[Output],
        profile: Option<&str>,
    ) -> Result<Vec<ApplyResult>, ApplyError> {
        match self.kind {
            Kind::Wlroots => {
                let mut results = wlr.apply_states(states)?;
                let extra = self.persist(&results, layout, profile);
                results.extend(extra);
                Ok(results)
            }
            Kind::Sway => self.sway_apply(wlr, states, layout, profile),
            Kind::Niri => self.niri_apply(wlr, states, layout, profile),
            Kind::Mango => self.mango_apply(wlr, states, layout, profile),
        }
    }

    /// Fall back to wlr-randr when the compositor's IPC tool is missing.
    fn apply_without_tool(
        &self,
        wlr: &dyn Wlr,
        states: &[OutputState],
        layout: &[Output],
        profile: Option<&str>,
    ) -> Result<Vec<ApplyResult>, ApplyError> {
        let mut results = wlr.apply_states(states)?;
        let extra = self.persist(&results, layout, profile);
        results.push(config_warning(format!(
            "{} was not found on PATH; applied with wlr-randr, so HDR and color settings \
             were skipped.",
            self.tool()
        )));
        results.extend(extra);
        Ok(results)
    }

