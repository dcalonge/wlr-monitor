    /// The arguments after `output <name>` for one output.
    pub fn sway_output_args(&self, state: &OutputState) -> Result<String, CompositorError> {
        // The result is a sway command string: `;` or `,` in a value would
        // chain more commands, so validate everything that is not a number.
        self.check_state(state)?;
        if !state.enabled {
            return Ok("disable".to_string());
        }
        let mut parts = vec!["enable".to_string()];
        if let Some(mode) = &state.mode {
            parts.push(format!(
                "mode {}@{}Hz",
                mode.size_text(),
                format_refresh_config(mode.refresh)
            ));
        }
        parts.push(format!("pos {} {}", state.x, state.y));
        parts.push(format!("scale {}", format_number(state.scale)));
        parts.push(format!("transform {}", state.transform));
        parts.push(format!(
            "adaptive_sync {}",
            if state.adaptive_sync { "on" } else { "off" }
        ));
        if let Some(depth) = state
            .bit_depth
            .filter(|d| self.capabilities.bit_depths.contains(d))
        {
            parts.push(format!("render_bit_depth {depth}"));
        }
        if let Some(hdr) = state.hdr.filter(|_| self.capabilities.hdr) {
            parts.push(format!("hdr {}", if hdr { "on" } else { "off" }));
        }
        if let Some(profile) = state.color_profile.as_deref().filter(|p| !p.is_empty())
            && self.color_profile_supported(profile)
        {
            match profile.strip_prefix("icc:") {
                Some(path) => parts.push(format!("color_profile icc {}", quote(path))),
                None => parts.push(format!("color_profile {profile}")),
            }
        }
        Ok(parts.join(" "))
    }

    fn sway_apply(
        &self,
        wlr: &dyn Wlr,
        states: &[OutputState],
        layout: &[Output],
        profile: Option<&str>,
    ) -> Result<Vec<ApplyResult>, ApplyError> {
        let Some(tool) = self.tool_path() else {
            return self.apply_without_tool(wlr, states, layout, profile);
        };
        // Build (and validate) every command before running any of them.
        let commands = apply_order(states)
            .iter()
            .map(|state| {
                Ok((
                    state.name.clone(),
                    format!(
                        "output {} {}",
                        quote(&state.name),
                        self.sway_output_args(state)?
                    ),
                ))
            })
            .collect::<Result<Vec<_>, CompositorError>>()?;
        let mut results: Vec<ApplyResult> = commands
            .into_iter()
            .map(|(name, command)| {
                run_apply_command(
                    &name,
                    vec![tool.clone(), "--".into(), command],
                    APPLY_TIMEOUT,
                    &[],
                    self.child_env(),
                )
            })
            .collect();
        let extra = self.persist(&results, layout, profile);
        results.extend(extra);
        Ok(results)
    }

