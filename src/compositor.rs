//! Compositor integrations.
//!
//! wlr-randr changes the live layout of any wlroots compositor, but forgets
//! it on restart. For sway, niri and mango the layout can also be written to
//! an include file the compositor's config loads, and extra settings (HDR,
//! bit depth, color profile) go through the compositor's own IPC tool.

mod mango;
mod niri;
mod source;
mod sway;

use std::collections::{BTreeMap, HashMap, HashSet};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::time::Duration;

use anyhow::{Context, Result, bail, ensure};
use clap::ValueEnum;
use serde::{Deserialize, Serialize};

use crate::apply::{Applied, ApplyResult, verify_layout};
use crate::exec::{run_tool, which};
use crate::fsutil::{write_if_changed, xdg_dir};
use crate::output::{Output, OutputState, is_printable, match_state};
use crate::wlr_randr::WlrRandr;

const HEADER: &str = "Generated by wlr-monitor; managed settings are rewritten on every apply.";
const QUERY_TIMEOUT: Duration = Duration::from_secs(5);

#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub enum Kind {
    /// A generic wlroots compositor: everything goes through wlr-randr.
    Wlroots,
    Mango,
    Sway,
    Niri,
}

impl Kind {
    /// Pick the running compositor from environment variables.
    pub fn detect(var: impl Fn(&str) -> Option<String>) -> Self {
        let set = |key: &str| var(key).is_some_and(|value| !value.is_empty());
        let desktop = var("XDG_CURRENT_DESKTOP")
            .unwrap_or_default()
            .to_lowercase();
        let in_desktop = |name: &str| desktop.split(':').any(|item| item.trim() == name);
        if set("MANGO_INSTANCE_SIGNATURE") || in_desktop("mango") {
            Self::Mango
        } else if set("SWAYSOCK") || in_desktop("sway") {
            Self::Sway
        } else if set("NIRI_SOCKET") || in_desktop("niri") {
            Self::Niri
        } else {
            Self::Wlroots
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Self::Wlroots => "wlroots",
            Self::Mango => "mango",
            Self::Sway => "sway",
            Self::Niri => "niri",
        }
    }

    /// The compositor's IPC command line tool.
    fn tool(self) -> &'static str {
        match self {
            Self::Wlroots => "",
            Self::Mango => "mmsg",
            Self::Sway => "swaymsg",
            Self::Niri => "niri",
        }
    }

    /// The config directory and file name of the include, if there is one.
    fn include_file(self) -> Option<(&'static str, &'static str)> {
        match self {
            Self::Wlroots => None,
            Self::Mango => Some(("mango", "wlr-monitor.conf")),
            Self::Sway => Some(("sway", "wlr-monitor.conf")),
            Self::Niri => Some(("niri", "wlr-monitor.kdl")),
        }
    }

    fn comment(self) -> &'static str {
        if self == Self::Niri { "//" } else { "#" }
    }

    fn note(self) -> &'static str {
        match self {
            Self::Wlroots => "",
            Self::Mango => {
                "Extra rule options you add (hdr_max_lum, primary, …) are kept on rewrite."
            }
            Self::Sway => "sway merges output commands: put bg, max_render_time, … in your config.",
            Self::Niri => {
                "niri uses the first matching output block: add layout {}, hot-corners, … here; they are kept."
            }
        }
    }

    /// The arguments of the IPC query that reports live settings.
    fn live_args(self) -> Option<&'static [&'static str]> {
        match self {
            Self::Wlroots => None,
            Self::Mango => Some(&["get", "all-monitors"]),
            Self::Sway => Some(sway::LIVE_ARGS),
            Self::Niri => Some(niri::LIVE_ARGS),
        }
    }

    fn default_capabilities(self) -> Capabilities {
        match self {
            Self::Wlroots => Capabilities::default(),
            Self::Mango => Capabilities {
                hdr: true,
                icc: true,
                ..Capabilities::default()
            },
            Self::Sway => Capabilities {
                hdr: true,
                bit_depths: &[6, 8, 10],
                color_presets: &["gamma22", "srgb"],
                icc: true,
            },
            // niri has no HDR or color management yet; max-bpc is the depth.
            Self::Niri => Capabilities {
                bit_depths: &[6, 8, 10, 12, 14, 16],
                ..Capabilities::default()
            },
        }
    }
}

/// The compositor-specific settings the integration can manage.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Capabilities {
    pub hdr: bool,
    pub bit_depths: &'static [u8],
    pub color_presets: &'static [&'static str],
    pub icc: bool,
}

impl Capabilities {
    pub fn color_profile(&self) -> bool {
        !self.color_presets.is_empty() || self.icc
    }
}

/// What the include writer reports back.
#[derive(Debug)]
pub struct Written {
    pub path: PathBuf,
    /// Set when only the sidecar state file could not be written.
    pub warning: Option<String>,
}

/// The include and sidecar contents from before a write.
#[derive(Debug)]
pub struct IncludeBackup {
    include: Option<Vec<u8>>,
    sidecar: Option<Vec<u8>>,
}

fn restore_file(path: &Path, bytes: Option<&[u8]>) -> Result<()> {
    match bytes {
        Some(bytes) => write_if_changed(path, bytes, 0o644)
            .with_context(|| format!("Could not restore {}", path.display())),
        None => match fs::remove_file(path) {
            Ok(()) => Ok(()),
            Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
            Err(error) => {
                Err(error).with_context(|| format!("Could not remove {}", path.display()))
            }
        },
    }
}

/// Shared by all outputs while rendering one include.
#[derive(Debug, Default)]
struct RenderContext {
    /// EDID identifiers used by more than one output. Those outputs must be
    /// matched by connector name instead.
    ambiguous: HashSet<String>,
    /// Option lines the user added by hand to the previous include, by
    /// match target.
    preserved: HashMap<String, Vec<String>>,
}

impl RenderContext {
    fn preserved(&self, target: &str) -> &[String] {
        self.preserved.get(target).map_or(&[], Vec::as_slice)
    }
}

/// The state behind the generated include, kept next to it.
///
/// It remembers settings the compositor cannot report back (color profile,
/// render bit depth, …) and the rules of disconnected outputs. It is not
/// part of the include itself because mango reads config lines into a
/// 512-byte buffer.
#[derive(Debug, Default, Serialize, Deserialize)]
struct Sidecar {
    include: PathBuf,
    outputs: BTreeMap<String, Saved>,
    profile: Option<String>,
}

#[derive(Debug, Serialize, Deserialize)]
struct Saved {
    #[serde(flatten)]
    state: OutputState,
    #[serde(default)]
    make: String,
    #[serde(default)]
    model: String,
    #[serde(default)]
    serial: String,
}

#[derive(Debug, Clone)]
pub struct Compositor {
    pub kind: Kind,
    /// Narrowed at runtime when the IPC shows an older compositor version.
    pub capabilities: Capabilities,
    /// False with `--no-include`: nothing is ever written.
    pub include_enabled: bool,
    /// The IPC tool to run (a name on `PATH` or a path).
    pub tool: String,
    include: Option<PathBuf>,
    home: PathBuf,
    config_home: PathBuf,
    state_home: PathBuf,
}

impl Compositor {
    pub fn new(kind: Kind, include: Option<&Path>, include_enabled: bool) -> Self {
        Self::with_dirs(
            kind,
            include,
            include_enabled,
            std::env::home_dir().unwrap_or_default(),
            xdg_dir("XDG_CONFIG_HOME", ".config"),
            xdg_dir("XDG_STATE_HOME", ".local/state"),
        )
    }

    pub fn with_dirs(
        kind: Kind,
        include: Option<&Path>,
        include_enabled: bool,
        home: PathBuf,
        config_home: PathBuf,
        state_home: PathBuf,
    ) -> Self {
        let mut compositor = Self {
            kind,
            capabilities: kind.default_capabilities(),
            include_enabled,
            tool: kind.tool().to_string(),
            include: None,
            home,
            config_home,
            state_home,
        };
        compositor.include = kind.include_file().map(|(dir, file)| match include {
            // Absolute, so the include line and the sourced check do not
            // depend on the directory wlr-monitor was started from.
            Some(path) => {
                let expanded = compositor.expand_tilde(&path.to_string_lossy());
                std::path::absolute(&expanded).unwrap_or_else(|_| expanded.into())
            }
            None => compositor.default_include(dir, file),
        });
        compositor
    }

    pub fn name(&self) -> &'static str {
        self.kind.name()
    }

    pub fn include_path(&self) -> Option<&Path> {
        self.include.as_deref()
    }

    /// True when the compositor refuses to load a config whose include is
    /// missing (niri), so the file has to exist before the line is added.
    pub fn include_must_exist(&self) -> bool {
        self.kind == Kind::Niri
    }

    fn default_include(&self, dir: &str, file: &str) -> PathBuf {
        match self.kind {
            // mango hard-codes `$HOME/.config/mango` and ignores XDG_CONFIG_HOME.
            Kind::Mango => self.mango_dir().join(file),
            _ => self.config_home.join(dir).join(file),
        }
    }

    fn mango_dir(&self) -> PathBuf {
        self.home.join(".config/mango")
    }

    fn expand_tilde(&self, path: &str) -> String {
        shellexpand::tilde_with_context(path, || Some(self.home.to_string_lossy())).into_owned()
    }

    /// Show paths below `$HOME` as `~/…` (compositors expand `~`).
    pub fn display_path(&self, path: &Path) -> String {
        match path.strip_prefix(&self.home) {
            Ok(relative) => format!("~/{}", relative.display()),
            Err(_) => path.display().to_string(),
        }
    }

    /// Where the sidecar state lives. A custom `--include` gets its own.
    fn state_path(&self) -> PathBuf {
        let (dir, file) = self.kind.include_file().unwrap_or_default();
        let custom = self.include.as_deref() != Some(&self.default_include(dir, file));
        let stem = match (&self.include, custom) {
            (Some(path), true) => {
                let slug: String = path
                    .to_string_lossy()
                    .chars()
                    .map(|c| if c.is_alphanumeric() { c } else { '_' })
                    .collect();
                format!("{}-{slug}", self.name())
            }
            _ => self.name().to_string(),
        };
        self.state_home
            .join(format!("wlr-monitor/{stem}-layout.json"))
    }

    // IPC

    /// The IPC tool's full path, or `None` when it is not installed.
    fn tool_path(&self) -> Option<String> {
        if self.tool.is_empty() {
            return None;
        }
        which(&self.tool).map(|path| path.to_string_lossy().into_owned())
    }

    /// Run the IPC query for live settings and return its output.
    pub fn query_live(&self) -> Option<String> {
        let args = self.kind.live_args()?;
        run_tool(&self.tool_path()?, args, QUERY_TIMEOUT).ok()
    }

    // Reading state

    fn read_sidecar(&self) -> Sidecar {
        // The sidecar only describes the include it was written with. If that
        // file is gone, belongs to another path, or is never updated again
        // (`--no-include`), it is ignored.
        let Some(include) = self
            .include
            .as_deref()
            .filter(|path| self.include_enabled && path.exists())
        else {
            return Sidecar::default();
        };
        fs::read_to_string(self.state_path())
            .ok()
            .and_then(|text| serde_json::from_str::<Sidecar>(&text).ok())
            .filter(|sidecar| sidecar.include == include)
            .unwrap_or_default()
    }

    /// The remembered outputs, with names filled in. Invalid entries are skipped.
    fn saved(&self) -> Vec<Saved> {
        let mut saved = Vec::new();
        for (name, mut entry) in self.read_sidecar().outputs {
            if entry.state.validate().is_ok() {
                entry.state.name = name;
                saved.push(entry);
            }
        }
        saved
    }

    /// Fill in compositor-specific settings wlr-randr cannot report.
    ///
    /// `live` is the output of `query_live()`, which the caller runs in
    /// parallel with wlr-randr.
    pub fn enrich(&mut self, outputs: &mut [Output], live: Option<&str>) {
        let saved: Vec<OutputState> = self.saved().into_iter().map(|entry| entry.state).collect();
        let connected: Vec<OutputState> = outputs.iter().map(Output::state).collect();
        for output in outputs.iter_mut() {
            if let Some(found) = match_state(&saved, &output.state(), &connected) {
                output.hdr = output.hdr.or(found.hdr);
                output.bit_depth = output.bit_depth.or(found.bit_depth);
                if output.color_profile.is_none() {
                    output.color_profile.clone_from(&found.color_profile);
                }
            }
        }
        if let Some(json) = live {
            match self.kind {
                Kind::Wlroots => {}
                Kind::Sway => sway::enrich(self, outputs, json),
                Kind::Niri => niri::enrich(self, outputs, json),
                Kind::Mango => mango::enrich(outputs, json),
            }
        }
        self.drop_unsupported(outputs);
    }

    /// Clear settings this compositor (version) cannot apply.
    ///
    /// Used after reading the live outputs and by `--print-config`, so a
    /// profile saved on another compositor does not show phantom changes.
    /// Unsupported settings are not shown in the UI and are silently dropped
    /// from profiles rather than refused.
    pub fn drop_unsupported(&self, outputs: &mut [Output]) {
        for output in outputs {
            if !self.capabilities.hdr {
                output.hdr = None;
            }
            if !self.bit_depth_supported(output.bit_depth) {
                output.bit_depth = None;
            }
            if output
                .color_profile
                .as_deref()
                .is_some_and(|profile| !self.color_profile_supported(profile))
            {
                output.color_profile = None;
            }
        }
    }

    fn bit_depth_supported(&self, depth: Option<u8>) -> bool {
        depth.is_some_and(|depth| self.capabilities.bit_depths.contains(&depth))
    }

    /// A color profile is a preset name or `icc:/absolute/path`.
    pub fn color_profile_supported(&self, value: &str) -> bool {
        // mango splits rule values on commas, so such paths cannot be written.
        if !is_printable(value) || (self.kind == Kind::Mango && value.contains(',')) {
            return false;
        }
        match value.strip_prefix("icc:") {
            // Compositors open the path as is, relative to their own directory.
            Some(path) => self.capabilities.icc && Path::new(path).is_absolute(),
            None => self.capabilities.color_presets.contains(&value),
        }
    }

    // The generated include

    /// Reject values that would not be safe to put in a config or command.
    ///
    /// Profiles are plain JSON files, so their strings are untrusted input.
    fn check_name(name: &str) -> Result<()> {
        ensure!(
            is_printable(name),
            "Refusing to write unprintable output name {name:?}."
        );
        Ok(())
    }

    /// Render the include for exactly `outputs` (see `layout_for_include`).
    pub fn render_include(&self, outputs: &[Output], profile: Option<&str>) -> Result<String> {
        let comment = self.kind.comment();
        let mut lines = vec![format!("{comment} {HEADER}")];
        if !self.kind.note().is_empty() {
            lines.push(format!("{comment} {}", self.kind.note()));
        }
        if let Some(profile) = profile.filter(|profile| !profile.is_empty()) {
            // Profile names end up in a config file: never let them add lines.
            let safe: String = profile.chars().filter(|c| !c.is_control()).collect();
            lines.push(format!("{comment} Profile: {safe}"));
        }
        lines.push(String::new());
        let context = self.context(outputs, self.preserved_options()?);
        match self.kind {
            Kind::Wlroots => {}
            Kind::Sway => lines.extend(sway::render(self, outputs, &context)?),
            Kind::Niri => lines.extend(niri::render(self, outputs, &context)?),
            Kind::Mango => lines.extend(mango::render(self, outputs, &context)?),
        }
        Ok(format!("{}\n", lines.join("\n").trim_end()))
    }

    fn context(
        &self,
        outputs: &[Output],
        preserved: HashMap<String, Vec<String>>,
    ) -> RenderContext {
        let mut counts: HashMap<String, usize> = HashMap::new();
        for output in outputs {
            *counts.entry(output.identifier()).or_default() += 1;
        }
        RenderContext {
            ambiguous: counts
                .into_iter()
                .filter(|(identifier, count)| !identifier.is_empty() && *count > 1)
                .map(|(identifier, _)| identifier)
                .collect(),
            preserved,
        }
    }

    /// The name used to match an output in the generated config.
    ///
    /// The EDID identifier survives connector renames (docks, MST hubs). It
    /// is skipped when two outputs share it (identical monitors often report
    /// the same serial) and when it is not printable, since EDID strings come
    /// from the monitor and must not be able to add config lines.
    fn target(output: &Output, context: &RenderContext) -> Result<String> {
        let identifier = output.identifier();
        if !identifier.is_empty()
            && !context.ambiguous.contains(&identifier)
            && is_printable(&identifier)
        {
            return Ok(identifier);
        }
        Self::check_name(&output.name)?;
        Ok(output.name.clone())
    }

    /// Hand-added options in the current include, keyed by match target.
    fn preserved_options(&self) -> Result<HashMap<String, Vec<String>>> {
        Ok(match self.kind {
            Kind::Niri => niri::preserved(&self.read_include_text()?),
            Kind::Mango => mango::preserved(&self.read_include_text()?),
            Kind::Wlroots | Kind::Sway => HashMap::new(),
        })
    }

    /// An include that is not valid UTF-8 is an error rather than empty:
    /// rewriting it would silently drop the user's own options.
    fn read_include_text(&self) -> Result<String> {
        let Some(path) = &self.include else {
            return Ok(String::new());
        };
        // A missing or unreadable file has nothing to preserve.
        let Ok(bytes) = fs::read(path) else {
            return Ok(String::new());
        };
        String::from_utf8(bytes).map_err(|_| {
            anyhow::anyhow!(
                "Could not read {}: it is not valid UTF-8.",
                self.display_path(path)
            )
        })
    }

    /// Outputs from the previous include that are not connected now.
    ///
    /// Keeping their rules means a dock monitor still gets its layout after
    /// the user applied something while undocked.
    fn retained_outputs(&self, current: &[Output]) -> Vec<Output> {
        let saved = self.saved();
        let connected: Vec<String> = current.iter().map(Output::hardware_id).collect();
        let saved_count = |id: &str| {
            saved
                .iter()
                .filter(|entry| entry.state.hardware_id == id)
                .count()
        };
        saved
            .iter()
            .filter(|entry| !current.iter().any(|output| output.name == entry.state.name))
            // The same monitor on another connector. Only trusted when its
            // EDID id is unique: identical monitors often share a serial, and
            // dropping the twin's rule would merge both onto one rule.
            .filter(|entry| {
                let id = &entry.state.hardware_id;
                id.is_empty() || saved_count(id) != 1 || !connected.contains(id)
            })
            .map(|entry| {
                let mut output = Output::new(&entry.state.name);
                output.description.clone_from(&entry.state.description);
                output.make.clone_from(&entry.make);
                output.model.clone_from(&entry.model);
                output.serial.clone_from(&entry.serial);
                entry.state.apply_to(&mut output, true);
                output
            })
            .collect()
    }

    /// `outputs` plus the remembered disconnected ones, validated.
    ///
    /// This is exactly what `write_include()` writes, so `--print-config`
    /// can show the same thing.
    pub fn layout_for_include(&self, outputs: &[Output]) -> Result<Vec<Output>> {
        let mut items = outputs.to_vec();
        items.extend(self.retained_outputs(outputs));
        items
            .iter()
            .try_for_each(|output| Self::check_name(&output.name))?;
        Ok(items)
    }

    /// Write the include, or return `None` when that is disabled.
    pub fn write_include(
        &self,
        outputs: &[Output],
        profile: Option<&str>,
    ) -> Result<Option<Written>> {
        let Some(path) = self.include.as_deref().filter(|_| self.include_enabled) else {
            return Ok(None);
        };
        let items = self.layout_for_include(outputs)?;
        let text = self.render_include(&items, profile)?;
        if path.is_symlink() {
            bail!(
                "{} is a symlink (managed by Home Manager or NixOS?). wlr-monitor needs a \
                 writable file; remove the link or pass --include to choose another path.",
                self.display_path(path)
            );
        }
        write_if_changed(path, text.as_bytes(), 0o644)
            .with_context(|| format!("Could not write {}", self.display_path(path)))?;

        let sidecar = Sidecar {
            include: path.to_path_buf(),
            profile: profile.map(str::to_string),
            outputs: items
                .iter()
                .map(|output| {
                    let saved = Saved {
                        state: output.state(),
                        make: output.make.clone(),
                        model: output.model.clone(),
                        serial: output.serial.clone(),
                    };
                    (output.name.clone(), saved)
                })
                .collect(),
        };
        let state_path = self.state_path();
        let text = serde_json::to_string_pretty(&sidecar)? + "\n";
        let warning = write_if_changed(&state_path, text.as_bytes(), 0o644)
            .err()
            .map(|error| {
                format!(
                    "Could not write {}: {error}. The include was written, but color settings \
                     and disconnected outputs will not be remembered.",
                    self.display_path(&state_path)
                )
            });
        Ok(Some(Written {
            path: path.to_path_buf(),
            warning,
        }))
    }

    /// The previous include and sidecar contents, used to undo a write when
    /// the compositor rejects the new settings.
    pub fn backup_include(&self) -> IncludeBackup {
        IncludeBackup {
            include: self.include.as_deref().and_then(|path| fs::read(path).ok()),
            sidecar: fs::read(self.state_path()).ok(),
        }
    }

    /// Put back a backup made by `backup_include`.
    pub fn restore_include(&self, backup: &IncludeBackup) -> Result<()> {
        let Some(path) = self.include.as_deref().filter(|_| self.include_enabled) else {
            return Ok(());
        };
        restore_file(path, backup.include.as_deref())?;
        restore_file(&self.state_path(), backup.sidecar.as_deref())
    }

    // Applying

    /// Apply `states` live. `layout` is the full layout the include gets
    /// written from afterwards (empty to skip that).
    pub fn apply(
        &self,
        wlr: &WlrRandr,
        states: &[OutputState],
        layout: &[Output],
        profile: Option<&str>,
    ) -> Result<Applied> {
        match self.kind {
            Kind::Wlroots => Ok(self.finish(wlr, wlr.apply(states), states, layout, profile)),
            Kind::Sway => sway::apply(self, wlr, states, layout, profile),
            Kind::Niri => niri::apply(self, wlr, states, layout, profile),
            Kind::Mango => mango::apply(self, wlr, states, layout, profile),
        }
    }

    /// Check that the requested settings actually took effect, then write the include.
    fn finish(
        &self,
        wlr: &WlrRandr,
        mut applied: Applied,
        states: &[OutputState],
        layout: &[Output],
        profile: Option<&str>,
    ) -> Applied {
        if !applied.succeeded() {
            return applied;
        }
        self.verify_layout(wlr, states, &mut applied);
        if !applied.succeeded() || layout.is_empty() {
            return applied;
        }
        match self.write_include(layout, profile) {
            Ok(written) => applied
                .warnings
                .extend(written.and_then(|written| written.warning)),
            Err(error) => applied.warnings.push(format!("{error:#}")),
        }
        applied
    }

    /// Fail outputs whose live state (read back from wlr-randr) does not match
    /// the requested settings. Covers enabled, mode, position, scale, transform
    /// and VRR — anything a compositor command may have silently ignored.
    fn verify_layout(&self, wlr: &WlrRandr, states: &[OutputState], applied: &mut Applied) {
        let Ok(live) = wlr.read() else { return };
        let failed = verify_layout(states, Some(&live), &applied.results);
        for result in applied
            .results
            .iter_mut()
            .filter(|result| result.error.is_none())
        {
            if failed.contains(&result.name) {
                result.error =
                    Some("the requested settings did not take effect on the output".to_string());
            }
        }
    }

    /// Fall back to wlr-randr when the compositor's IPC tool is missing.
    fn apply_without_tool(
        &self,
        wlr: &WlrRandr,
        states: &[OutputState],
        layout: &[Output],
        profile: Option<&str>,
    ) -> Applied {
        let mut applied = self.finish(wlr, wlr.apply(states), states, layout, profile);
        applied.warnings.push(format!(
            "{} was not found on PATH; applied with wlr-randr, so HDR and color settings were skipped.",
            self.tool
        ));
        applied
    }
}

/// Quote a value for sway and niri configs and commands.
fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The same result for every state (one command applied them all).
fn same_result(states: &[OutputState], result: Result<()>) -> Vec<ApplyResult> {
    let error = result.err().map(|error| format!("{error:#}"));
    states
        .iter()
        .map(|state| ApplyResult {
            name: state.name.clone(),
            error: error.clone(),
        })
        .collect()
}

