    // niri
    // ------------------------------------------------------------------

    fn niri_render_output(
        &self,
        output: &Output,
        context: &RenderContext,
    ) -> Result<Vec<String>, CompositorError> {
        self.check_state(&output.state())?;
        let target = self.target(output, context)?;
        let preserved = context.preserved(&target);
        let on_demand = niri_on_demand(preserved);
        let mut lines = vec![format!("output {} {{", quote(&target))];
        if !output.enabled {
            lines.push("    off".to_string());
        } else {
            if let Some(mode) = &output.mode {
                lines.push(format!(
                    "    mode \"{}@{}\"",
                    mode.size_text(),
                    format_refresh_config(mode.refresh)
                ));
            }
            lines.push(format!("    scale {}", format_number(output.scale)));
            lines.push(format!("    transform \"{}\"", output.transform));
            lines.push(format!("    position x={} y={}", output.x, output.y));
            if output.adaptive_sync && !on_demand {
                lines.push("    variable-refresh-rate".to_string());
            }
            // Same gate as the live command: niri up to 25.11 rejects the
            // whole config on an unknown max-bpc node.
            if let Some(depth) = output
                .bit_depth
                .filter(|_| self.bit_depth_supported(output.bit_depth))
            {
                lines.push(format!("    max-bpc {depth}"));
            }
        }
        for line in preserved {
            if on_demand
                && !output.adaptive_sync
                && line.trim().starts_with("variable-refresh-rate")
            {
                continue; // VRR was switched off in the TUI
            }
            lines.push(line.clone());
        }
        lines.push("}".to_string());
        Ok(lines)
    }

    pub fn niri_output_commands(
        &self,
        state: &OutputState,
        on_demand: bool,
    ) -> Result<Vec<Vec<String>>, CompositorError> {
        self.check_state(state)?;
        let owned = |items: &[&str]| {
            items
                .iter()
                .map(|item| item.to_string())
                .collect::<Vec<_>>()
        };
        if !state.enabled {
            return Ok(vec![owned(&["off"])]);
        }
        let mut commands = vec![owned(&["on"])];
        if let Some(mode) = &state.mode {
            commands.push(vec![
                "mode".into(),
                format!(
                    "{}@{}",
                    mode.size_text(),
                    format_refresh_config(mode.refresh)
                ),
            ]);
        }
        commands.push(vec!["scale".into(), format_number(state.scale)]);
        commands.push(vec!["transform".into(), state.transform.clone()]);
        commands.push(vec![
            "position".into(),
            "set".into(),
            "--".into(),
            state.x.to_string(),
            state.y.to_string(),
        ]);
        let mut vrr = owned(&["vrr", if state.adaptive_sync { "on" } else { "off" }]);
        if state.adaptive_sync && on_demand {
            vrr.push("--on-demand".into());
        }
        commands.push(vrr);
        if let Some(depth) = state
            .bit_depth
            .filter(|_| self.bit_depth_supported(state.bit_depth))
        {
            commands.push(vec!["max-bpc".into(), depth.to_string()]);
        }
        Ok(commands)
    }

    fn on_demand_for(&self, outputs: &[Output]) -> Result<HashMap<String, bool>, CompositorError> {
        let preserved = self.preserved_options()?;
        if preserved.is_empty() {
            return Ok(HashMap::new());
        }
        let context = self.render_context(outputs, preserved);
        Ok(outputs
            .iter()
            .filter_map(|output| {
                let target = self.target(output, &context).ok()?;
                Some((
                    output.name.clone(),
                    niri_on_demand(context.preserved(&target)),
                ))
            })
            .collect())
    }

    fn niri_apply(
        &self,
        wlr: &dyn Wlr,
        states: &[OutputState],
        layout: &[Output],
        profile: Option<&str>,
    ) -> Result<Vec<ApplyResult>, ApplyError> {
        let Some(tool) = self.tool_path() else {
            return self.apply_without_tool(wlr, states, layout, profile);
        };
        // An unreadable include only loses the on-demand hint here; writing
        // it afterwards fails and is reported as a warning.
        let on_demand = self.on_demand_for(layout).unwrap_or_default();
        // Build (and validate) every command first, like sway, so a bad state
        // cannot leave earlier outputs applied and the include unwritten.
        let plan = apply_order(states)
            .iter()
            .map(|state| {
                let flag = on_demand.get(&state.name).copied().unwrap_or(false);
                Ok((state.name.clone(), self.niri_output_commands(state, flag)?))
            })
            .collect::<Result<Vec<_>, CompositorError>>()?;
        let mut results = Vec::new();
        for (name, commands) in plan {
            let mut result = ApplyResult::success(name.clone(), Vec::new());
            for args in commands {
                let mut command = vec![tool.clone(), "msg".into(), "output".into(), name.clone()];
                command.extend(args);
                result = run_apply_command(&name, command, APPLY_TIMEOUT, &[], self.child_env());
                if !result.ok {
                    break;
                }
            }
            results.push(result);
        }
        let extra = self.persist(&results, layout, profile);
        results.extend(extra);
        Ok(results)
    }

