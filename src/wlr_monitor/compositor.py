COMPOSITORS: dict[str, type[Compositor]] = {
    "wlroots": Compositor,
    "mango": Mango,
    "sway": Sway,
    "niri": Niri,
}


def detect_compositor(
    name: str | None = None,
    *,
    env: Mapping[str, str] | None = None,
    include_path: Path | str | None = None,
    write_include: bool = True,
) -> Compositor:
    """Pick the integration for the running compositor."""
    environ = dict(os.environ if env is None else env)
    kind = (name or "auto").lower()
    if kind == "auto":
        desktops = {
            item.strip().lower()
            for item in environ.get("XDG_CURRENT_DESKTOP", "").split(":")
        }
        if environ.get("MANGO_INSTANCE_SIGNATURE") or "mango" in desktops:
            kind = "mango"
        elif environ.get("SWAYSOCK") or "sway" in desktops:
            kind = "sway"
        elif environ.get("NIRI_SOCKET") or "niri" in desktops:
            kind = "niri"
        else:
            kind = "wlroots"
    if kind not in COMPOSITORS:
        raise ValueError(f"Unknown compositor {name!r}.")
    return COMPOSITORS[kind](
        env=environ, include_path=include_path, write_include=write_include
    )


class Backend:
    """wlr-randr plus the detected compositor integration."""

    def __init__(
        self,
        wlr: WlrRandr | None = None,
        compositor: Compositor | None = None,
    ) -> None:
        self.wlr = wlr if wlr is not None else WlrRandr()
        self.compositor = compositor if compositor is not None else detect_compositor()

    def read_outputs(self) -> list[Output]:
        outputs = self.wlr.read_outputs()
        try:
            self.compositor.enrich(outputs)
        except (OSError, ValueError, TypeError, KeyError, AttributeError):
            # IPC extras are best effort; wlr-randr's view is still valid.
            pass
        return outputs

    def target_layout(self, states: Iterable[OutputState]) -> list[Output]:
        """The full layout after applying ``states`` to the live outputs."""
        try:
            outputs = self.read_outputs()
        except WlrRandrError:
            return []
        by_name = {state.name: state for state in states}
        for output in outputs:
            state = by_name.get(output.name)
            if state is not None:
                state.apply_to(output, restore=True)
        return outputs

    def apply_states(
        self, states: Iterable[OutputState], *, profile: str | None = None
    ) -> list[ApplyResult]:
        items = list(states)
        layout = self.target_layout(items) if self.compositor.supports_include else []
        return self.compositor.apply(self.wlr, items, layout, profile=profile)

    def write_include(self, *, profile: str | None = None) -> Path | None:
        """Write the include from the live layout (``--init-include``)."""
        return self.compositor.write_include(self.read_outputs(), profile=profile)
