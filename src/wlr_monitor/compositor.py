def _quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _printable(value: str) -> bool:
    """True if ``value`` cannot break out of a config line (no newlines etc.)."""
    return all(character.isprintable() for character in value)


def _unique_by_hardware(
    entries: Mapping[str, dict[str, Any]], hardware_id: str, connected: list[str]
) -> dict[str, Any] | None:
    """The saved entry for an EDID id, if both sides make it unambiguous."""
    if connected.count(hardware_id) != 1:
        return None
    matches = [raw for raw in entries.values() if raw.get("hardware_id") == hardware_id]
    return matches[0] if len(matches) == 1 else None


class Sway(Compositor):
    """sway: ``swaymsg output …`` for live changes, ``include`` for persistence."""

    name = "sway"
    label = "sway"
    default_capabilities = Capabilities(
        hdr=True,
        bit_depths=(6, 8, 10),
        color_presets=("gamma22", "srgb"),
        icc=True,
    )
    tool = "swaymsg"
    config_dir = "sway"
    include_filename = "wlr-monitor.conf"
    note = "sway merges output commands: put bg, max_render_time, … in your config."

    def include_line(self) -> str:
        path = self.include_path()
        return f"include {self.display_path(path)}" if path else ""

    def main_config_paths(self) -> list[Path]:
        home = self.home()
        config = self.config_home()
        return [
            home / ".sway" / "config",
            config / "sway" / "config",
            home / ".i3" / "config",
            config / "i3" / "config",
            Path("/etc/sway/config"),
        ]

    def _include_refs(self, text: str, base: Path) -> list[Path]:
        refs: list[Path] = []
        for line in text.splitlines():
            match = re.match(r"\s*include\s+(.+?)\s*$", line)
            if not match:
                continue
            raw = match.group(1).strip().strip("'\"")
            expanded = str(self.expand(raw, base))
            matches = glob.glob(expanded)
            refs.extend(Path(item) for item in (matches or [expanded]))
        return refs

    def output_args(self, state: OutputState) -> str:
        """The arguments after ``output <name>`` for one output."""
        # The result is a sway command string: `;` or `,` in a value would
        # chain more commands, so validate everything that is not a number.
        self.check_state(state)
        if not state.enabled:
            return "disable"
        parts = ["enable"]
        if state.mode is not None:
            parts.append(
                f"mode {state.mode.size_text}@"
                f"{format_refresh_config(state.mode.refresh)}Hz"
            )
        parts.append(f"pos {state.x} {state.y}")
        parts.append(f"scale {format_number(state.scale)}")
        parts.append(f"transform {state.transform}")
        parts.append(f"adaptive_sync {'on' if state.adaptive_sync else 'off'}")
        caps = self.capabilities
        if state.bit_depth is not None and state.bit_depth in caps.bit_depths:
            parts.append(f"render_bit_depth {state.bit_depth}")
        if state.hdr is not None and caps.hdr:
            parts.append(f"hdr {'on' if state.hdr else 'off'}")
        profile = state.color_profile
        if profile and self.color_profile_supported(profile):
            if profile.startswith("icc:"):
                parts.append(f"color_profile icc {_quote(profile[4:])}")
            else:
                parts.append(f"color_profile {profile}")
        return " ".join(parts)

    def render_output(
        self, output: Output, context: RenderContext | None = None
    ) -> list[str]:
        target = self.target(output, context)
        return [f"output {_quote(target)} {self.output_args(output.state())}"]

    def apply(
        self,
        wlr: WlrRandr,
        states: list[OutputState],
        layout: list[Output],
        *,
        profile: str | None = None,
    ) -> list[ApplyResult]:
        tool = self.tool_path()
        if tool is None:
            return self._apply_without_tool(wlr, states, layout, profile)
        commands = [
            (state.name, f"output {_quote(state.name)} {self.output_args(state)}")
            for state in apply_order(states)
        ]
        results = [
            run_apply_command(name, [tool, "--", command], env=self.env)
            for name, command in commands
        ]
        return results + self._persist(results, layout, profile)

    def _enrich_live(self, outputs: list[Output]) -> None:
        tool = self.tool_path()
        if tool is None:
            return
        data = self._query([tool, "-t", "get_outputs", "-r"])
        if not isinstance(data, list):
            return
        items = [item for item in data if isinstance(item, dict)]
        if items and not any("hdr" in item for item in items):
            # get_outputs gained "hdr" in sway 1.11, together with the hdr
            # command and the gamma22/srgb color profiles.
            self.capabilities = replace(
                self.default_capabilities, hdr=False, color_presets=()
            )
        by_name = {item.get("name"): item for item in items}
        for output in outputs:
            item = by_name.get(output.name)
            if item is None:
                continue
            if "hdr" in item:
                output.hdr = bool(item["hdr"])
            status = item.get("adaptive_sync_status")
            if status in ("enabled", "disabled"):
                output.adaptive_sync = status == "enabled"


