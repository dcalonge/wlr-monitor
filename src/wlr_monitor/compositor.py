_MANGO_REGEX_SPECIAL = re.compile(r"([.^$*+?()\[\]{}|\\])")


class Mango(Compositor):
    """mango: ``monitor_rule`` lines in an include, applied with ``reload_config``.

    mango keeps adaptive sync in sync with the monitor rule's ``vrr`` value
    and switches it off again whenever focus changes, so VRR set through
    wlr-randr does not stick. Writing the rule and reloading is the only
    way to change VRR persistently; it also carries HDR and ICC settings.
    """

    name = "mango"
    label = "mango"
    default_capabilities = Capabilities(hdr=True, icc=True)
    tool = "mmsg"
    config_dir = "mango"
    include_filename = "wlr-monitor.conf"
    note = "Extra rule options you add (hdr_max_lum, primary, …) are kept on rewrite."
    # monitor_rule keys this file generates; anything else is kept.
    MANAGED = frozenset(
        {
            "name",
            "make",
            "model",
            "serial",
            "width",
            "height",
            "refresh",
            "x",
            "y",
            "scale",
            "rr",
            "vrr",
            "hdr",
            "icc",
            "disable",
        }
    )
    MATCH_KEYS = ("name", "make", "model", "serial")

    def mango_dir(self) -> Path:
        # mango hard-codes $HOME/.config/mango and ignores XDG_CONFIG_HOME.
        return self.home() / ".config" / "mango"

    def include_path(self) -> Path | None:
        if self._include_override is not None:
            return self._include_override
        return self.mango_dir() / self.include_filename

    def expand(self, raw: str, base: Path) -> Path:
        # Same rules as mango's resolve_config_path(): "./x" is relative to
        # the config directory (not the including file), "~/x" to $HOME and
        # anything else is used as is.
        if raw.startswith("./"):
            return self.mango_dir() / raw[2:]
        if raw == "~" or raw.startswith("~/"):
            return Path(str(self.home()) + raw[1:])
        return Path(raw)

    def include_line(self) -> str:
        path = self.include_path()
        return f"source_optional={self.display_path(path)}" if path else ""

    def main_config_paths(self) -> list[Path]:
        config = self.mango_dir()
        return [
            config / "config.conf",
            config / "config.toml",
            Path("/etc/mango/config.conf"),
            Path("/etc/mango/config.toml"),
        ]

    def _include_refs(self, text: str, base: Path) -> list[Path]:
        refs: list[Path] = []
        for line in text.splitlines():
            match = re.match(r"\s*source(?:_optional)?\s*=\s*(.+?)\s*$", line)
            if not match:
                continue
            refs.append(self.expand(match.group(1).strip().strip("'\""), base))
        return refs

    def color_profile_supported(self, value: str) -> bool:
        # mango splits rule values on commas, so such paths cannot be written.
        return super().color_profile_supported(value) and "," not in value

    def rule_match(self, output: Output, context: RenderContext | None = None) -> str:
        parts = (output.make, output.model, output.serial)
        ambiguous = context.ambiguous if context is not None else frozenset()
        if (
            all(parts)
            and output.identifier not in ambiguous
            and not any("," in part or not _printable(part) for part in parts)
        ):
            return f"make:{output.make},model:{output.model},serial:{output.serial}"
        if not _printable(output.name):
            raise CompositorError(
                f"Refusing to write unprintable output name {output.name!r}."
            )
        escaped = _MANGO_REGEX_SPECIAL.sub(r"\\\1", output.name)
        return f"name:^{escaped}$"

    def preserved_options(self) -> dict[str, tuple[str, ...]]:
        """Unmanaged ``key:value`` fields of each generated monitor rule."""
        preserved: dict[str, tuple[str, ...]] = {}
        for line in self._read_include_text().splitlines():
            if not line.startswith("monitor_rule="):
                continue
            fields = line[len("monitor_rule=") :].split(",")
            match = ",".join(
                field
                for field in fields
                if field.split(":", 1)[0].strip() in self.MATCH_KEYS
            )
            kept = tuple(
                field.strip()
                for field in fields
                if ":" in field and field.split(":", 1)[0].strip() not in self.MANAGED
            )
            if match:
                preserved[match] = kept
        return preserved

    def render_output(
        self, output: Output, context: RenderContext | None = None
    ) -> list[str]:
        self.check_state(output.state())
        match = self.rule_match(output, context)
        preserved = tuple(context.preserved.get(match, ())) if context else ()
        if not output.enabled:
            return ["monitor_rule=" + ",".join([match, "disable:1", *preserved])]
        fields = [match]
        if output.mode is not None:
            refresh = format_refresh_config(output.mode.refresh)
            refresh = refresh.rstrip("0").rstrip(".")
            fields.extend(
                [
                    f"width:{output.mode.width}",
                    f"height:{output.mode.height}",
                    f"refresh:{refresh}",
                ]
            )
        fields.extend(
            [
                f"x:{output.x}",
                f"y:{output.y}",
                f"scale:{format_number(output.scale)}",
                f"rr:{TRANSFORMS.index(output.transform)}",
                f"vrr:{1 if output.adaptive_sync else 0}",
            ]
        )
        if output.hdr is not None:
            fields.append(f"hdr:{1 if output.hdr else 0}")
        if output.color_profile and self.color_profile_supported(output.color_profile):
            fields.append(f"icc:{output.color_profile[4:]}")
        fields.extend(preserved)
        line = "monitor_rule=" + ",".join(fields)
        if len(line) > MANGO_MAX_LINE:
            raise CompositorError(
                f"The monitor rule for {output.name} is longer than mango's "
                f"{MANGO_MAX_LINE}-character line limit (shorten the ICC path)."
            )
        return [line]

    def _mmsg(self, tool: str, name: str, *args: str) -> ApplyResult:
        return run_apply_command(
            name, [tool, *args], error_markers=('"error"', "Error:"), env=self.env
        )

    def apply(
        self,
        wlr: WlrRandr,
        states: list[OutputState],
        layout: list[Output],
        *,
        profile: str | None = None,
    ) -> list[ApplyResult]:
        tool = self.tool_path()
        if layout and self.write_include_enabled and self.include_is_sourced():
            warnings: list[ApplyResult] = []
            try:
                self.write_include(layout, profile=profile)
            except StateFileError as exc:
                # The rules are written; only the sidecar is missing.
                warnings.append(
                    ApplyResult(name="config", command=[], ok=True, warning=str(exc))
                )
            except CompositorError as exc:
                return [
                    ApplyResult(name=state.name, command=[], ok=False, error=str(exc))
                    for state in states
                ]
            if tool is None:
                # mango reloads sourced files itself (auto_reload_config=1).
                warnings.append(
                    ApplyResult(
                        name="config",
                        command=[],
                        ok=True,
                        warning=(
                            "mmsg was not found; relying on mango's "
                            "auto_reload_config to pick up the new monitor rules."
                        ),
                    )
                )
                return [
                    ApplyResult(name=state.name, command=[], ok=True)
                    for state in states
                ] + warnings
            reload = self._mmsg(tool, "config", "dispatch", "reload_config")
            return [
                ApplyResult(
                    name=state.name,
                    command=reload.command,
                    ok=reload.ok,
                    stdout=reload.stdout,
                    stderr=reload.stderr,
                    error=reload.error,
                )
                for state in states
            ] + warnings

        # Not sourced yet: apply what the protocol can do and explain the rest.
        results = wlr.apply_states(states)
        if tool is not None and all(result.ok for result in results):
            for state in apply_order(states):
                if state.enabled and state.hdr is not None:
                    mode = "on" if state.hdr else "off"
                    results.append(
                        self._mmsg(
                            tool,
                            state.name,
                            "dispatch",
                            f"togglehdr,{mode},{state.name}",
                        )
                    )
        extra = self._persist(results, layout, profile)
        if any(state.enabled and state.adaptive_sync for state in states):
            if self.write_include_enabled:
                advice = (
                    f"Add `{self.include_line()}` to your mango config so the "
                    "generated monitor rules carry VRR."
                )
            else:
                advice = "With --no-include, VRR will not stick."
            extra.append(
                ApplyResult(
                    name="config",
                    command=[],
                    ok=True,
                    warning=(
                        "mango switches VRR off again unless it comes from a "
                        f"monitor_rule. {advice}"
                    ),
                )
            )
        return results + extra

    def _enrich_live(self, outputs: list[Output]) -> None:
        tool = self.tool_path()
        if tool is None:
            return
        data = self._query([tool, "get", "all-monitors"])
        monitors = data.get("monitors") if isinstance(data, dict) else None
        if not isinstance(monitors, list):
            return
        by_name = {
            item.get("name"): item for item in monitors if isinstance(item, dict)
        }
        for output in outputs:
            item = by_name.get(output.name)
            if isinstance(item, dict) and "is_hdr" in item:
                output.hdr = bool(item["is_hdr"])


