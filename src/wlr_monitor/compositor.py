class Niri(Compositor):
    """niri: ``niri msg output …`` for live changes, ``include`` for persistence."""

    name = "niri"
    label = "niri"
    # niri has no HDR or color management yet; max-bpc is the color depth.
    default_capabilities = Capabilities(bit_depths=(6, 8, 10, 12, 14, 16))
    tool = "niri"
    config_dir = "niri"
    include_filename = "wlr-monitor.kdl"
    comment = "//"
    include_must_exist = True
    note = (
        "niri uses the first matching output block: add layout {}, hot-corners, "
        "… here; they are kept."
    )
    # Top-level output nodes this file generates; anything else is kept.
    MANAGED = frozenset(
        {"off", "on", "mode", "scale", "transform", "position", "max-bpc"}
    )

    def include_line(self) -> str:
        path = self.include_path()
        if path is None:
            return ""
        main = self.main_config()
        if main is not None and path.parent == main.parent:
            return f'include "{path.name}"'
        return f"include {_quote(str(path))}"

    def main_config_paths(self) -> list[Path]:
        paths: list[Path] = []
        override = self.env.get("NIRI_CONFIG")
        if override:
            paths.append(Path(override).expanduser())
        paths.append(self.config_home() / "niri" / "config.kdl")
        paths.append(Path("/etc/niri/config.kdl"))
        return paths

    def _include_refs(self, text: str, base: Path) -> list[Path]:
        refs: list[Path] = []
        for line in text.splitlines():
            stripped = line.strip()
            if stripped.startswith("//"):
                continue
            match = re.match(r'include\b[^"]*"((?:[^"\\]|\\.)*)"', stripped)
            if not match:
                continue
            refs.append(self.expand(match.group(1), base))
        return refs

    def preserved_options(self) -> dict[str, tuple[str, ...]]:
        """Unmanaged lines of each generated ``output`` block.

        The generated file has a fixed shape (``output "…" {`` at column 0,
        ``}`` closing it), so a brace-depth scan is enough. Nested blocks such
        as ``layout { … }`` are kept verbatim, as is a hand-written
        ``variable-refresh-rate on-demand=true``.
        """
        preserved: dict[str, tuple[str, ...]] = {}
        target: str | None = None
        kept: list[str] = []
        depth = 0
        for line in self._read_include_text().splitlines():
            stripped = line.strip()
            if target is None:
                match = re.match(r'output\s+"((?:[^"\\]|\\.)*)"\s*\{\s*$', line)
                if match:
                    target = match.group(1).replace('\\"', '"').replace("\\\\", "\\")
                    kept, depth = [], 1
                continue
            opens, closes = stripped.count("{"), stripped.count("}")
            if depth == 1 and stripped == "}":
                preserved[target] = tuple(kept)
                target = None
                continue
            node = stripped.split(None, 1)[0] if stripped else ""
            managed = depth == 1 and (
                node in self.MANAGED
                or (node == "variable-refresh-rate" and "on-demand" not in stripped)
            )
            if stripped and not managed:
                kept.append(line.rstrip())
            depth += opens - closes
        return preserved

    @staticmethod
    def _on_demand(preserved: tuple[str, ...]) -> bool:
        return any(
            line.strip().startswith("variable-refresh-rate") and "on-demand" in line
            for line in preserved
        )

    def render_output(
        self, output: Output, context: RenderContext | None = None
    ) -> list[str]:
        self.check_state(output.state())
        target = self.target(output, context)
        preserved = tuple(context.preserved.get(target, ())) if context else ()
        on_demand = self._on_demand(preserved)
        lines = [f"output {_quote(target)} {{"]
        if not output.enabled:
            lines.append("    off")
        else:
            if output.mode is not None:
                lines.append(
                    f'    mode "{output.mode.size_text}@'
                    f'{format_refresh_config(output.mode.refresh)}"'
                )
            lines.append(f"    scale {format_number(output.scale)}")
            lines.append(f'    transform "{output.transform}"')
            lines.append(f"    position x={output.x} y={output.y}")
            if output.adaptive_sync and not on_demand:
                lines.append("    variable-refresh-rate")
            # Same gate as the live command: niri up to 25.11 rejects the
            # whole config on an unknown max-bpc node.
            if self._bit_depth_supported(output.bit_depth):
                lines.append(f"    max-bpc {output.bit_depth}")
        for line in preserved:
            if (
                on_demand
                and not output.adaptive_sync
                and (line.strip().startswith("variable-refresh-rate"))
            ):
                continue  # VRR was switched off in the TUI
            lines.append(line)
        lines.append("}")
        return lines

    def output_commands(
        self, state: OutputState, *, on_demand: bool = False
    ) -> list[list[str]]:
        self.check_state(state)
        if not state.enabled:
            return [["off"]]
        commands = [["on"]]
        if state.mode is not None:
            commands.append(
                [
                    "mode",
                    f"{state.mode.size_text}@{format_refresh_config(state.mode.refresh)}",
                ]
            )
        commands.append(["scale", format_number(state.scale)])
        commands.append(["transform", state.transform])
        commands.append(["position", "set", "--", str(state.x), str(state.y)])
        vrr = ["vrr", "on" if state.adaptive_sync else "off"]
        if state.adaptive_sync and on_demand:
            vrr.append("--on-demand")
        commands.append(vrr)
        if self._bit_depth_supported(state.bit_depth):
            commands.append(["max-bpc", str(state.bit_depth)])
        return commands

    def _bit_depth_supported(self, depth: int | None) -> bool:
        return depth is not None and depth in self.capabilities.bit_depths

    def _on_demand_for(self, outputs: list[Output]) -> dict[str, bool]:
        preserved = self.preserved_options()
        if not preserved:
            return {}
        context = self.render_context(outputs, preserved)
        result: dict[str, bool] = {}
        for output in outputs:
            try:
                target = self.target(output, context)
            except CompositorError:
                continue
            result[output.name] = self._on_demand(preserved.get(target, ()))
        return result

    def apply(
        self,
        wlr: WlrRandr,
        states: list[OutputState],
        layout: list[Output],
        *,
        profile: str | None = None,
    ) -> list[ApplyResult]:
        tool = self.tool_path()
        if tool is None:
            return self._apply_without_tool(wlr, states, layout, profile)
        on_demand = self._on_demand_for(layout)
        # Build (and validate) every command first, like sway, so a bad state
        # cannot leave earlier outputs applied and the include unwritten.
        plan = [
            (
                state.name,
                self.output_commands(state, on_demand=on_demand.get(state.name, False)),
            )
            for state in apply_order(states)
        ]
        results: list[ApplyResult] = []
        for name, commands in plan:
            result = ApplyResult(name=name, command=[], ok=True)
            for args in commands:
                result = run_apply_command(
                    name, [tool, "msg", "output", name, *args], env=self.env
                )
                if not result.ok:
                    break
            results.append(result)
        return results + self._persist(results, layout, profile)

    def _enrich_live(self, outputs: list[Output]) -> None:
        tool = self.tool_path()
        if tool is None:
            return
        data = self._query([tool, "msg", "--json", "outputs"])
        if isinstance(data, list):
            data = {item.get("name"): item for item in data if isinstance(item, dict)}
        if not isinstance(data, dict):
            return
        items = [item for item in data.values() if isinstance(item, dict)]
        if items and not any("max_bpc" in item for item in items):
            # max-bpc arrived after niri 25.11, together with this IPC field.
            self.capabilities = replace(self.default_capabilities, bit_depths=())
        on_demand = self._on_demand_for(outputs)
        for output in outputs:
            if on_demand.get(output.name):
                # With on-demand VRR, vrr_enabled only reflects the focused
                # window; the include says VRR is configured on.
                output.adaptive_sync = True
                continue
            item = data.get(output.name)
            if isinstance(item, dict) and "vrr_enabled" in item:
                output.adaptive_sync = bool(item["vrr_enabled"])


