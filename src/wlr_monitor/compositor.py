"""Compositor integrations: detection, native apply and config includes.

wlr-randr speaks the generic wlr-output-management protocol. That is enough
for position, mode, scale and transform on every wlroots compositor, but:

* HDR, color depth and color management are compositor-specific;
* mango re-applies its own ``monitor_rule`` VRR setting on every focus change,
  so adaptive sync enabled through wlr-randr switches itself off again;
* layouts applied through the protocol are lost on restart or config reload.

Each integration below therefore knows how to read the extra state from the
compositor's IPC tool, apply output states natively (``swaymsg``,
``niri msg``, ``mmsg``) and render the layout as a small config file that the
user includes once from their compositor config. The generated file lives in
the compositor's config directory as a normal, writable file, so it also works
when the main config is a read-only Home Manager / NixOS store symlink.
"""

