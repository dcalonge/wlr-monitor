HEADER = "Generated by wlr-monitor; managed settings are rewritten on every apply."
# mango reads config lines into a 512-byte buffer (including the newline).
MANGO_MAX_LINE = 510


class CompositorError(RuntimeError):
    """Raised when the generated compositor config cannot be written."""


class StateFileError(CompositorError):
    """The include was written, but the sidecar state file was not.

    The compositor already has the new layout, so callers treat this as a
    warning rather than a failed apply.
    """


@dataclass(frozen=True)
class Capabilities:
    """Compositor-specific settings the integration can manage."""

    hdr: bool = False
    bit_depths: tuple[int, ...] = ()
    color_presets: tuple[str, ...] = ()
    icc: bool = False

    @property
    def color_profile(self) -> bool:
        return bool(self.color_presets) or self.icc


@dataclass(frozen=True)
class RenderContext:
    """Information shared by all outputs while rendering one include.

    ``ambiguous`` holds EDID identifiers used by more than one output (those
    must be matched by connector name instead). ``preserved`` maps a match
    target to option lines the user added by hand to the previous include.
    """

    ambiguous: frozenset[str] = frozenset()
    preserved: Mapping[str, tuple[str, ...]] = field(default_factory=dict)


def format_refresh_config(value: float) -> str:
    """Refresh rate with the three decimals sway, niri and mango expect."""
    return f"{value:.3f}"


def color_profile_label(value: str | None) -> str:
    if not value:
        return "default"
    if value.startswith("icc:"):
        return f"ICC {value[4:]}"
    return value


def _atomic_write(path: Path, text: str, *, display: str) -> None:
    """Replace ``path`` with ``text`` unless it already has that content."""
    try:
        if path.exists() and path.read_text(encoding="utf-8") == text:
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, temp_name = tempfile.mkstemp(
            prefix=f".{path.name}.", suffix=".tmp", dir=path.parent, text=True
        )
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                handle.write(text)
            os.chmod(temp_name, 0o644)
            os.replace(temp_name, path)
        except BaseException:
            try:
                os.unlink(temp_name)
            except OSError:
                pass
            raise
    except OSError as exc:
        raise CompositorError(f"Could not write {display}: {exc}") from exc


class Compositor:
    """A generic wlroots compositor: everything goes through wlr-randr."""

    name: ClassVar[str] = "wlroots"
    label: ClassVar[str] = "wlroots"
    default_capabilities: ClassVar[Capabilities] = Capabilities()
    tool: ClassVar[str] = ""
    config_dir: ClassVar[str] = ""
    include_filename: ClassVar[str] = ""
    comment: ClassVar[str] = "#"
    note: ClassVar[str] = ""
    # True when the compositor refuses to load a config whose include is
    # missing (niri), so the file has to exist before the line is added.
    include_must_exist: ClassVar[bool] = False

    def __init__(
        self,
        *,
        env: Mapping[str, str] | None = None,
        include_path: Path | str | None = None,
        write_include: bool = True,
    ) -> None:
        self.env = dict(os.environ if env is None else env)
        # Absolute, so the suggested include line and the sourced check do
        # not depend on the directory wlr-monitor was started from.
        self._include_override = (
            Path(os.path.abspath(Path(include_path).expanduser()))
            if include_path is not None
            else None
        )
        self.write_include_enabled = write_include
        # Narrowed at runtime when the IPC shows an older compositor version.
        self.capabilities = self.default_capabilities

    # ------------------------------------------------------------------
    # Paths
    # ------------------------------------------------------------------

    @property
    def supports_include(self) -> bool:
        return bool(self.include_filename)

    def home(self) -> Path:
        home = self.env.get("HOME")
        return Path(home) if home else Path.home()

    def config_home(self) -> Path:
        base = self.env.get("XDG_CONFIG_HOME")
        return Path(base) if base else self.home() / ".config"

    def include_path(self) -> Path | None:
        if not self.supports_include:
            return None
        if self._include_override is not None:
            return self._include_override
        return self.config_home() / self.config_dir / self.include_filename

    def state_path(self) -> Path:
        """Sidecar JSON with the full state behind the generated include.

        It keeps settings the compositor cannot report back (color profile,
        render bit depth, …) and the rules of disconnected outputs. It is kept
        out of the include itself because mango reads config lines into a
        512-byte buffer. A custom ``--include`` gets its own sidecar.
        """
        base = self.env.get("XDG_STATE_HOME")
        root = Path(base) if base else self.home() / ".local" / "state"
        stem = f"{self.name}-layout"
        if self._include_override is not None:
            digest = hashlib.sha256(str(self._include_override).encode()).hexdigest()[
                :12
            ]
            stem = f"{self.name}-{digest}-layout"
        return root / "wlr-monitor" / f"{stem}.json"

    def display_path(self, path: Path) -> str:
        """Show paths below $HOME as ``~/…`` (compositors expand ``~``)."""
        try:
            return "~/" + str(path.relative_to(self.home()))
        except ValueError:
            return str(path)

    def expand(self, raw: str, base: Path) -> Path:
        """Resolve a path from a config line: ``~``, $VARS and relative paths."""
        if raw == "~" or raw.startswith("~/"):
            raw = str(self.home()) + raw[1:]
        raw = os.path.expandvars(raw)
        return Path(raw) if os.path.isabs(raw) else base / raw

    def include_line(self) -> str:
        """The line the user adds to their compositor config."""
        return ""

    def main_config_paths(self) -> list[Path]:
        return []

    def main_config(self) -> Path | None:
        return next((path for path in self.main_config_paths() if path.exists()), None)

    def _include_refs(self, text: str, base: Path) -> list[Path]:
        """Files referenced by include/source lines of a config file."""
        return []

    def include_is_sourced(self) -> bool:
        """Best-effort check that the main config includes our file.

        Follows one level of nested includes, which covers the common
        "config.conf sources monitors.conf" layout.
        """
        target = self.include_path()
        main = self.main_config()
        if target is None or main is None:
            return False
        wanted = os.path.realpath(target)
        pending: list[tuple[Path, int]] = [(main, 0)]
        seen: set[str] = set()
        while pending:
            config, depth = pending.pop()
            real = os.path.realpath(config)
            if real in seen:
                continue
            seen.add(real)
            try:
                text = config.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            for ref in self._include_refs(text, config.parent):
                if os.path.realpath(ref) == wanted:
                    return True
                if depth < 1 and ref.is_file():
                    pending.append((ref, depth + 1))
        return False

    def include_hint(self) -> str:
        """A short setup hint, or an empty string when nothing is needed."""
        path = self.include_path()
        if path is None or not self.write_include_enabled:
            return ""
        if self.include_is_sourced():
            return ""
        main = self.main_config()
        where = self.display_path(main) if main is not None else "your config"
        return (
            f"Add `{self.include_line()}` to {where} to keep layouts after a restart."
        )

    # ------------------------------------------------------------------
    # IPC helpers
    # ------------------------------------------------------------------

    def tool_path(self) -> str | None:
        if not self.tool:
            return None
        return shutil.which(self.tool, path=self.env.get("PATH"))

    def _query(self, command: list[str]) -> Any:
        """Run an IPC query and decode its JSON output, or return ``None``."""
        try:
            completed = subprocess.run(
                command,
                capture_output=True,
                text=True,
                timeout=5,
                check=False,
                env=self.env,
            )
        except (OSError, subprocess.TimeoutExpired):
            return None
        if completed.returncode != 0:
            return None
        try:
            return json.loads(completed.stdout)
        except json.JSONDecodeError:
            return None

    # ------------------------------------------------------------------
    # Reading state
    # ------------------------------------------------------------------

    def read_include_state(self) -> dict[str, Any]:
        """Load the sidecar state written together with the include.

        The sidecar only describes the include it was written with: if that
        file is gone (the user deleted it to start over), belongs to another
        path, or writing is disabled (--no-include, so it would never be
        updated again), the sidecar is ignored.
        """
        include = self.include_path()
        if include is None or not self.write_include_enabled or not include.exists():
            return {}
        try:
            data = json.loads(self.state_path().read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return {}
        if not isinstance(data, dict) or data.get("include") != str(include):
            return {}
        return data

    def enrich(self, outputs: list[Output]) -> None:
        """Fill in compositor-specific settings wlr-randr cannot report."""
        saved = self.read_include_state().get("outputs")
        if isinstance(saved, dict):
            entries = {
                str(name): raw for name, raw in saved.items() if isinstance(raw, dict)
            }
            connected = [output.hardware_id for output in outputs]
            for output in outputs:
                raw = entries.get(output.name)
                if raw is None and output.hardware_id:
                    raw = _unique_by_hardware(entries, output.hardware_id, connected)
                if raw is None:
                    continue
                try:
                    state = OutputState.from_dict(output.name, raw)
                except (KeyError, TypeError, ValueError):
                    continue
                if output.hdr is None:
                    output.hdr = state.hdr
                if output.bit_depth is None:
                    output.bit_depth = state.bit_depth
                if output.color_profile is None:
                    output.color_profile = state.color_profile
        self._enrich_live(outputs)
        self.drop_unsupported(outputs)

    def _enrich_live(self, outputs: list[Output]) -> None:
        """Override settings with live values from the compositor IPC."""

    def drop_unsupported(self, outputs: Iterable[Output]) -> None:
        """Clear settings this compositor (version) cannot apply.

        Called after reading and after copying a profile onto the outputs, so
        a profile saved on another compositor does not show phantom changes.
        """
        caps = self.capabilities
        for output in outputs:
            if not caps.hdr:
                output.hdr = None
            if output.bit_depth is not None and output.bit_depth not in caps.bit_depths:
                output.bit_depth = None
            if output.color_profile is not None and not self.color_profile_supported(
                output.color_profile
            ):
                output.color_profile = None

    def color_profile_supported(self, value: str) -> bool:
        caps = self.capabilities
        if not _printable(value):
            return False
        if value.startswith("icc:"):
            # Compositors open the path as is (mango does no ~ expansion and
            # resolves relative paths against its own working directory).
            return caps.icc and os.path.isabs(value[4:])
        return value in caps.color_presets

    # ------------------------------------------------------------------
    # Generated include
    # ------------------------------------------------------------------

    def render_include(
        self, outputs: Iterable[Output], *, profile: str | None = None
    ) -> str:
        """Render the include for exactly ``outputs`` (see layout_for_include)."""
        items = list(outputs)
        lines = [f"{self.comment} {HEADER}"]
        if self.note:
            lines.append(f"{self.comment} {self.note}")
        if profile:
            # Profile names end up in a config file: never let them add lines.
            safe = "".join(char for char in profile if char.isprintable())
            lines.append(f"{self.comment} Profile: {safe}")
        lines.append("")
        context = self.render_context(items)
        for output in items:
            lines.extend(self.render_output(output, context))
        return "\n".join(lines).rstrip("\n") + "\n"

    def render_context(
        self,
        outputs: list[Output],
        preserved: Mapping[str, tuple[str, ...]] | None = None,
    ) -> RenderContext:
        counts = Counter(output.identifier for output in outputs if output.identifier)
        return RenderContext(
            ambiguous=frozenset(key for key, count in counts.items() if count > 1),
            preserved=self.preserved_options() if preserved is None else preserved,
        )

    def target(self, output: Output, context: RenderContext | None = None) -> str:
        """Name used to match an output in the generated config.

        The EDID identifier survives connector renames (docks, MST hubs). It
        is skipped when two outputs share it (identical monitors often report
        the same serial) and when it is not printable, since EDID strings come
        from the monitor and must not be able to add config lines.
        """
        ambiguous = context.ambiguous if context is not None else frozenset()
        identifier = output.identifier
        if identifier and identifier not in ambiguous and _printable(identifier):
            return identifier
        if not _printable(output.name):
            raise CompositorError(
                f"Refusing to write unprintable output name {output.name!r}."
            )
        return output.name

    def render_output(
        self, output: Output, context: RenderContext | None = None
    ) -> list[str]:
        return []

    def preserved_options(self) -> dict[str, tuple[str, ...]]:
        """Hand-added options in the current include, keyed by match target."""
        return {}

    def _read_include_text(self) -> str:
        path = self.include_path()
        if path is None:
            return ""
        try:
            return path.read_text(encoding="utf-8")
        except OSError:
            return ""

    def check_state(self, state: OutputState) -> None:
        """Reject values that would not be safe to put in a config or command.

        Profiles are plain JSON files, so their strings are untrusted input.
        """
        if state.transform not in TRANSFORMS:
            raise CompositorError(
                f"{state.name}: invalid transform {state.transform!r}."
            )
        if not _printable(state.name):
            raise CompositorError(f"Invalid output name {state.name!r}.")

    def _sidecar_entry(self, output: Output) -> dict[str, Any]:
        entry = output.state().to_dict()
        entry.update(make=output.make, model=output.model, serial=output.serial)
        return entry

    def retained_outputs(self, current: list[Output]) -> list[Output]:
        """Outputs from the previous include that are not connected now.

        Keeping their rules means a dock monitor still gets its layout after
        the user applied something while undocked.
        """
        saved = self.read_include_state().get("outputs")
        if not isinstance(saved, dict):
            return []
        names = {output.name for output in current}
        connected = [output.hardware_id for output in current if output.hardware_id]
        saved_hardware = Counter(
            str(raw.get("hardware_id") or "")
            for raw in saved.values()
            if isinstance(raw, dict)
        )
        retained: list[Output] = []
        for name, raw in saved.items():
            if not isinstance(raw, dict) or name in names:
                continue
            try:
                state = OutputState.from_dict(str(name), raw)
            except (KeyError, TypeError, ValueError):
                continue
            # The same monitor, now on another connector. Only trusted when
            # the EDID id is unique: identical monitors often share a serial,
            # and dropping the twin's rule would merge both onto one rule.
            if (
                state.hardware_id
                and saved_hardware[state.hardware_id] == 1
                and state.hardware_id in connected
            ):
                continue
            output = Output(
                name=str(name),
                description=state.description,
                make=str(raw.get("make") or ""),
                model=str(raw.get("model") or ""),
                serial=str(raw.get("serial") or ""),
            )
            state.apply_to(output, restore=True)
            output.mode = state.mode
            retained.append(output)
        return retained

    def layout_for_include(self, outputs: Iterable[Output]) -> list[Output]:
        """``outputs`` plus the remembered disconnected ones, validated.

        This is exactly what write_include() writes, so --print-config can
        show the same thing.
        """
        items = list(outputs)
        items.extend(self.retained_outputs(items))
        for output in items:
            self.check_state(output.state())
        return items

    def write_include(
        self, outputs: Iterable[Output], *, profile: str | None = None
    ) -> Path | None:
        """Atomically write the include. Returns the path, or None if disabled.

        Raises StateFileError (a CompositorError) when only the sidecar could
        not be written; the include itself is already in place then.
        """
        path = self.include_path()
        if path is None or not self.write_include_enabled:
            return None
        items = self.layout_for_include(outputs)
        text = self.render_include(items, profile=profile)
        if path.is_symlink():
            raise CompositorError(
                f"{self.display_path(path)} is a symlink (managed by Home Manager "
                "or NixOS?). wlr-monitor needs a writable file; remove the link "
                "or pass --include to choose another path."
            )
        state = {
            "profile": profile,
            "include": str(path),
            "outputs": {output.name: self._sidecar_entry(output) for output in items},
        }
        _atomic_write(path, text, display=self.display_path(path))
        try:
            _atomic_write(
                self.state_path(),
                json.dumps(state, indent=2, sort_keys=True) + "\n",
                display=self.display_path(self.state_path()),
            )
        except CompositorError as exc:
            raise StateFileError(
                f"{exc}. The include was written, but color settings and "
                "disconnected outputs will not be remembered."
            ) from exc
        return path

    def _persist(
        self,
        results: list[ApplyResult],
        layout: list[Output],
        profile: str | None,
    ) -> list[ApplyResult]:
        """Write the include after a successful live apply."""
        if not layout or any(not result.ok for result in results):
            return []
        try:
            self.write_include(layout, profile=profile)
        except CompositorError as exc:
            return [ApplyResult(name="config", command=[], ok=True, warning=str(exc))]
        return []

    # ------------------------------------------------------------------
    # Applying
    # ------------------------------------------------------------------

    def apply(
        self,
        wlr: WlrRandr,
        states: list[OutputState],
        layout: list[Output],
        *,
        profile: str | None = None,
    ) -> list[ApplyResult]:
        results = wlr.apply_states(states)
        return results + self._persist(results, layout, profile)

    def _apply_without_tool(
        self,
        wlr: WlrRandr,
        states: list[OutputState],
        layout: list[Output],
        profile: str | None,
    ) -> list[ApplyResult]:
        """Fall back to wlr-randr when the compositor's IPC tool is missing."""
        results = wlr.apply_states(states)
        warning = ApplyResult(
            name="config",
            command=[],
            ok=True,
            warning=(
                f"{self.tool} was not found on PATH; applied with wlr-randr, so "
                "HDR and color settings were skipped."
            ),
        )
        return [*results, warning, *self._persist(results, layout, profile)]


